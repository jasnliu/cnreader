const fs = require('fs');
const path = require('path');

const UNIT_COUNT = 10;
const ITEMS_PER_UNIT = 100;
const projectRoot = __dirname;

function sourcePath(folder, baseName, unitNumber) {
  const suffix = unitNumber === 1 ? '' : String(unitNumber);
  return path.join(projectRoot, folder, baseName + suffix + '.txt');
}

function readSourceLines(filePath) {
  return fs.readFileSync(filePath, 'utf8')
    .split(/\r?\n/)
    .map(function (line) { return line.trim().normalize('NFC'); })
    .filter(function (line) { return line.length > 0; });
}

const seenPhrases = new Set();
const units = [];

for (let unitNumber = 1; unitNumber <= UNIT_COUNT; unitNumber++) {
  const phrases = readSourceLines(sourcePath('Phrases', 'phrases', unitNumber));
  const pinyin = readSourceLines(sourcePath('PPinyin', 'pinyin', unitNumber));
  const definitions = readSourceLines(
    sourcePath('PDefinitions', 'pdefinitions', unitNumber)
  );

  const sources = { phrases: phrases, pinyin: pinyin, definitions: definitions };
  Object.keys(sources).forEach(function (field) {
    if (sources[field].length !== ITEMS_PER_UNIT) {
      throw new Error(
        'Unit ' + unitNumber + ' ' + field + ' has ' + sources[field].length
        + ' entries; expected ' + ITEMS_PER_UNIT + '.'
      );
    }
  });

  phrases.forEach(function (phrase) {
    if (seenPhrases.has(phrase)) {
      throw new Error('Duplicate phrase across units: ' + phrase);
    }
    seenPhrases.add(phrase);
  });

  units.push(sources);
}

const output = [
  '// Generated by generate-phrase-data.js. Edit the aligned text sources instead.',
  'window.CHINESE_READER_PHRASE_UNITS = ' + JSON.stringify(units, null, 2) + ';',
  '',
  '// Backward-compatible alias for consumers that use the first phrase unit.',
  'window.CHINESE_READER_PHRASE_DATA = window.CHINESE_READER_PHRASE_UNITS[0];',
  '',
].join('\n');

fs.writeFileSync(path.join(projectRoot, 'phrase-data.js'), output, 'utf8');
console.log('Compiled ' + seenPhrases.size + ' phrases across ' + units.length + ' units.');
